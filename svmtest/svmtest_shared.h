#pragma once
#if defined(_KERNEL_MODE) || defined(_NTDDK_)
#include <ntddk.h>
#else
#include <Windows.h>
#include <winioctl.h>
#endif

#define SVMTEST_DEVICE_TYPE 0x8337
#define IOCTL_SVMTEST_QUERY_CAPABILITIES CTL_CODE(SVMTEST_DEVICE_TYPE, 0x800, METHOD_BUFFERED, FILE_READ_ACCESS)
#define IOCTL_SVMTEST_RUN_SMOKE CTL_CODE(SVMTEST_DEVICE_TYPE, 0x801, METHOD_BUFFERED, FILE_READ_ACCESS | FILE_WRITE_ACCESS)
#define IOCTL_SVMTEST_RUN_CPUID CTL_CODE(SVMTEST_DEVICE_TYPE, 0x804, METHOD_BUFFERED, FILE_READ_ACCESS | FILE_WRITE_ACCESS)
#define IOCTL_SVMTEST_QUERY_RESULT CTL_CODE(SVMTEST_DEVICE_TYPE, 0x802, METHOD_BUFFERED, FILE_READ_ACCESS)
#define IOCTL_SVMTEST_RESET CTL_CODE(SVMTEST_DEVICE_TYPE, 0x803, METHOD_BUFFERED, FILE_WRITE_ACCESS)
#define IOCTL_SVMTEST_RUN_FULL_NESTED CTL_CODE(SVMTEST_DEVICE_TYPE, 0x805, METHOD_BUFFERED, FILE_READ_ACCESS | FILE_WRITE_ACCESS)
#define IOCTL_SVMTEST_RUN_MSR_TEST CTL_CODE(SVMTEST_DEVICE_TYPE, 0x806, METHOD_BUFFERED, FILE_READ_ACCESS | FILE_WRITE_ACCESS)

#define SVMTEST_PROTOCOL_VERSION 3u
#define SVMTEST_FLAG_SVM_SUPPORTED 0x00000001u
#define SVMTEST_FLAG_L0_DETECTED 0x00000002u
#define SVMTEST_FLAG_NESTED_SVM_READY 0x00000004u
#define SVMTEST_FLAG_SVMDIS_CLEAR 0x00000008u
#define SVMTEST_FLAG_NRIP_SAVE 0x00000010u
#define SVMTEST_FLAG_SVME_ENABLED 0x00000020u
#define SVMTEST_FLAG_SVM_READY 0x00000040u

#define SVMTEST_STAGE_NONE 0u
#define SVMTEST_STAGE_CAPABILITIES 1u
#define SVMTEST_STAGE_ALLOCATION 2u
#define SVMTEST_STAGE_GUEST_SETUP 3u
#define SVMTEST_STAGE_PIN_PROCESSOR 4u
#define SVMTEST_STAGE_SET_HSAVE 5u
#define SVMTEST_STAGE_VMMCALL 6u
#define SVMTEST_STAGE_CPUID 7u
#define SVMTEST_STAGE_MSR 8u
#define SVMTEST_STAGE_EXCEPTION 9u
#define SVMTEST_STAGE_BREAKPOINT SVMTEST_STAGE_EXCEPTION
#define SVMTEST_STAGE_NESTED_VMRUN 10u
#define SVMTEST_STAGE_CLEANUP 11u
#define SVMTEST_STAGE_COMPLETE 12u
#define SVMTEST_STAGE_CPUID_RESUME 13u

#define SVMTEST_MODE_CPUID 0u
#define SVMTEST_MODE_FULL_SMOKE 1u
#define SVMTEST_MODE_NESTED_FULL 2u
#define SVMTEST_MODE_MSR_TRANSPARENCY 3u

#define SVMTEST_CPUID_LEAF 0x53564D54u
#define SVMTEST_CPUID_RETURN_EAX 0x4C305445u
#define SVMTEST_CPUID_MARKER 0x43505549u
#define SVMTEST_CPUID_RESULT_MARKER 0x43505254u
#define SVMTEST_L1_HANDLER_MARKER 0x4C314841u
#define SVMTEST_L2_RESUME_MARKER 0x4C325253u

#define SVMTEST_EXIT_RECORD_COUNT 8u
#define SVMTEST_PASS_VMMCALL 0x00000001u
#define SVMTEST_PASS_CPUID 0x00000002u
#define SVMTEST_PASS_MSR 0x00000004u
#define SVMTEST_PASS_EXCEPTION 0x00000008u
#define SVMTEST_PASS_BREAKPOINT SVMTEST_PASS_EXCEPTION
#define SVMTEST_PASS_NESTED_VMRUN 0x00000010u

typedef struct _SVMTEST_CAPABILITIES
{
    ULONG Version;
    ULONG Size;
    LONG Status;
    ULONG Flags;
    ULONG SvmRevision;
    ULONG MaximumAsid;
    ULONG SvmFeaturesEdx;
    ULONG Reserved;
    UINT64 Efer;
    UINT64 VmCr;
    UINT64 VmHsavePa;
    CHAR CpuVendor[16];
    CHAR HypervisorVendor[16];
} SVMTEST_CAPABILITIES, *PSVMTEST_CAPABILITIES;

typedef struct _SVMTEST_RUN_REQUEST
{
    ULONG Version;
    ULONG Size;
    ULONG Iterations;
    ULONG Mode;
} SVMTEST_RUN_REQUEST, *PSVMTEST_RUN_REQUEST;

typedef struct _SVMTEST_EXIT_RECORD
{
    UINT64 ExitCode;
    UINT64 ExitInfo1;
    UINT64 ExitInfo2;
    UINT64 GuestRip;
    UINT64 ObservedNrip;
    UINT64 ExpectedNrip;
} SVMTEST_EXIT_RECORD, *PSVMTEST_EXIT_RECORD;

typedef struct _SVMTEST_RESULT
{
    ULONG Version;
    ULONG Size;
    LONG Status;
    ULONG Stage;
    ULONG PassedMask;
    ULONG IterationsRequested;
    ULONG IterationsCompleted;
    ULONG ProcessorGroup;
    ULONG ProcessorNumber;
    ULONG VmcbPhysicalAddressLow;
    ULONG VmcbPhysicalAddressHigh;
    ULONG HsavePhysicalAddressLow;
    ULONG HsavePhysicalAddressHigh;
    UINT64 GuestMagic;
    ULONG VmmcallExitCount;
    ULONG CpuidExitCount;
    ULONG MsrExitCount;
    ULONG ExceptionExitCount;
    ULONG NestedVmrunExitCount;
    ULONG ExceptionInjectionCount;
    ULONG NestedVmrunGpCount;
    ULONG NestedEnterCount;
    ULONG NestedReflectCount;
    ULONG NestedReturnCount;
    ULONG L1HandlerObservedMarker;
    ULONG L1HandlerObservedRax;
    ULONG L1HandlerObservedRbx;
    ULONG L1HandlerObservedRcx;
    ULONG L2ResumeMarker;
    ULONG Mode;
    ULONG CpuidLeaf;
    ULONG CpuidExitObservedEax;
    ULONG CpuidExpectedEax;
    ULONG CpuidObservedEax;
    UINT64 MsrEferInitial;
    UINT64 MsrEferAfterWrite;
    UINT64 MsrEferReadBack;
    UINT64 MsrVmCrInitial;
    UINT64 MsrVmCrAfterWrite;
    UINT64 MsrVmCrReadBack;
    UINT64 MsrVmHsavePaInitial;
    UINT64 MsrVmHsavePaAfterWrite;
    UINT64 MsrVmHsavePaReadBack;
    ULONG MsrTestPassed;
    ULONG MsrTransparencyDetected;
    SVMTEST_EXIT_RECORD Exits[SVMTEST_EXIT_RECORD_COUNT];
} SVMTEST_RESULT, *PSVMTEST_RESULT;

static_assert(sizeof(SVMTEST_CAPABILITIES) == 88, "SVMTEST_CAPABILITIES size");
static_assert(sizeof(SVMTEST_RUN_REQUEST) == 16, "SVMTEST_RUN_REQUEST size");
static_assert(sizeof(SVMTEST_EXIT_RECORD) == 48, "SVMTEST_EXIT_RECORD size");
static_assert(sizeof(SVMTEST_RESULT) == 632, "SVMTEST_RESULT size");
